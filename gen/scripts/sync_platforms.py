#!/usr/bin/env python3
"""Refresh the checked-in RTL snapshots from the two platform repositories."""

import argparse
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

GEN = Path(__file__).resolve().parents[1]
UTILS = GEN / "generator-app" / "src" / "utils"
PLATFORMS = {
    "eulsukdo": ("https://github.com/VARZero/EULSUKDO_LSQ.git", "gen/src/RTL"),
    "oryukdo": ("https://github.com/VARZero/ORYUKDO.git", "RTL"),
}


def run(*args):
    return subprocess.check_output(args, text=True).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for platform, (url, _) in PLATFORMS.items():
        parser.add_argument(f"--{platform}-repo", default=url)
    args = parser.parse_args()

    with tempfile.TemporaryDirectory(prefix="youngdo-platforms-") as temp:
        staged = Path(temp)
        versions = {}
        for platform, (_, subdir) in PLATFORMS.items():
            url = getattr(args, f"{platform}_repo")
            checkout = staged / platform
            subprocess.run(["git", "clone", "--quiet", "--depth", "1", url, str(checkout)], check=True)
            source = checkout / subdir
            files = sorted(source.glob("*.sv"))
            if not files or not (source / "eulsukdo_scheduler.sv").is_file():
                raise RuntimeError(f"{platform}: scheduler or RTL sources missing at {subdir}")
            versions[platform] = {
                "repository": PLATFORMS[platform][0],
                "commit": run("git", "-C", str(checkout), "rev-parse", "HEAD"),
                "path": subdir,
            }
            shutil.copytree(source, staged / f"{platform}_rtl")

        imports = []
        entries = []
        for platform in PLATFORMS:
            files = sorted((staged / f"{platform}_rtl").glob("*.sv"))
            for index, source in enumerate(files):
                symbol = f"{platform}_{index}"
                imports.append(
                    f"import {symbol} from '../../../platforms/{platform}/RTL/{source.name}?raw';"
                )
                entries.append((platform, source.name, symbol))
        lines = [
            "// Generated by gen/scripts/sync_platforms.py. Do not edit by hand.",
            *imports,
            "",
            "export const rtlSourceSets: Record<'eulsukdo' | 'oryukdo', Record<string, string>> = {",
        ]
        for platform in PLATFORMS:
            lines.append(f"  {platform}: {{")
            lines.extend(
                f"    {json.dumps(name)}: {symbol},"
                for owner, name, symbol in entries if owner == platform
            )
            lines.append("  },")
        lines.extend([
            "};",
            f"export const sourceVersions = {json.dumps(versions, ensure_ascii=False, indent=2)} as const;",
            "",
        ])

        # Stage both repositories successfully before changing any checked-in sources.
        for platform in PLATFORMS:
            target = GEN / "platforms" / platform / "RTL"
            if target.exists():
                shutil.rmtree(target)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(staged / f"{platform}_rtl", target)
        (UTILS / "platformSources.ts").write_text("\n".join(lines), encoding="utf-8")
        (GEN / "platforms" / "versions.json").write_text(
            json.dumps(versions, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        for platform, version in versions.items():
            print(f"{platform}: {version['commit']} ({version['path']})")


if __name__ == "__main__":
    main()
