#!/usr/bin/env python3
"""Bundle EULSUKDO Gen2 from a pinned commit or an explicitly selected ref."""
import argparse
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

GEN = Path(__file__).resolve().parents[1]
URL = "https://github.com/VARZero/EULSUKDO.git"
SOURCE_PATH = "gen2/src/RTL"


def git(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--local-repo", type=Path, help="Use a local checkout's committed sources")
    parser.add_argument("--ref", help="Revision to update to; otherwise keep the bundled commit")
    args = parser.parse_args()
    lock = GEN / "platforms/versions.json"
    with tempfile.TemporaryDirectory(prefix="youngdo-gen2-") as temp:
        repo = args.local_repo
        ref = args.ref or ("HEAD" if repo else json.loads(lock.read_text(encoding="utf-8"))["eulsukdo"]["commit"])
        if repo is None:
            repo = Path(temp)
            subprocess.run(["git", "init", "--quiet", str(repo)], check=True)
            subprocess.run(["git", "-C", str(repo), "fetch", "--quiet", "--depth", "1", URL, ref], check=True)
            ref = "FETCH_HEAD"
        commit = git(repo, "rev-parse", f"{ref}^{{commit}}").decode().strip()
        names = git(repo, "ls-tree", "--name-only", f"{commit}:{SOURCE_PATH}").decode().splitlines()
        sources = {name: git(repo, "show", f"{commit}:{SOURCE_PATH}/{name}") for name in names if name.endswith(".sv")}
        if "eulsukdo_scheduler.sv" not in sources or b"STRUCT_IST_BANKS" not in sources["eulsukdo_scheduler.sv"]:
            raise RuntimeError("Selected revision does not contain the current Gen2 scheduler")
        version = {"repository": URL, "commit": commit, "path": SOURCE_PATH,
                   "sha256": {name: hashlib.sha256(data).hexdigest() for name, data in sources.items()}}
        target = GEN / "platforms/eulsukdo/RTL"
        target.mkdir(parents=True, exist_ok=True)
        for old in target.glob("*.sv"):
            if old.name not in sources:
                old.unlink()
        for name, data in sources.items():
            (target / name).write_bytes(data)
        versions = {"eulsukdo": version}
        lines = ["// Generated by gen/scripts/sync_platforms.py. Do not edit by hand."]
        for index, name in enumerate(sources):
            lines.append(f"import rtl_{index} from '../../../platforms/eulsukdo/RTL/{name}?raw';")
        lines.extend(["", "export const rtlSourceSets = {", "  eulsukdo: {"])
        for index, name in enumerate(sources):
            lines.append(f"    {json.dumps(name)}: rtl_{index},")
        lines.extend(["  },", "};", f"export const sourceVersions = {json.dumps(versions, indent=2)} as const;", ""])
        (GEN / "generator-app/src/utils/platformSources.ts").write_text("\n".join(lines), encoding="utf-8")
        lock.write_text(json.dumps(versions, indent=2) + "\n", encoding="utf-8")
        print(f"eulsukdo: {commit} ({SOURCE_PATH}, {len(sources)} sources)")


if __name__ == "__main__":
    main()
