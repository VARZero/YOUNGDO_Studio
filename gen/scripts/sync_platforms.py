#!/usr/bin/env python3
"""Bundle pinned Gen2 platforms; update only the explicitly selected platform."""
import argparse
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

GEN = Path(__file__).resolve().parents[1]
URLS = {name: f"https://github.com/VARZero/{name.upper()}.git" for name in ["eulsukdo", "oryukdo"]}
SOURCE_PATH = "gen2/src/RTL"


def git(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", choices=URLS, help="Update one platform; otherwise reproduce all pinned platforms")
    parser.add_argument("--local-repo", type=Path, help="Use a local checkout's committed sources")
    parser.add_argument("--ref", help="Revision to update to; otherwise keep the bundled commit")
    args = parser.parse_args()
    if (args.local_repo or args.ref) and not args.platform:
        parser.error("--platform is required with --local-repo or --ref")
    lock = GEN / "platforms/versions.json"
    versions = json.loads(lock.read_text(encoding="utf-8"))
    selected = [args.platform] if args.platform else list(versions)
    for platform in selected:
        with tempfile.TemporaryDirectory(prefix="youngdo-gen2-") as temp:
            repo = args.local_repo
            ref = args.ref or ("HEAD" if repo else versions[platform]["commit"])
            if repo is None:
                repo = Path(temp)
                subprocess.run(["git", "init", "--quiet", str(repo)], check=True)
                subprocess.run(["git", "-C", str(repo), "fetch", "--quiet", "--depth", "1", URLS[platform], ref], check=True)
                ref = "FETCH_HEAD"
            commit = git(repo, "rev-parse", f"{ref}^{{commit}}").decode().strip()
            names = git(repo, "ls-tree", "--name-only", f"{commit}:{SOURCE_PATH}").decode().splitlines()
            sources = {name: git(repo, "show", f"{commit}:{SOURCE_PATH}/{name}") for name in names if name.endswith(".sv")}
            top = f"{platform}_scheduler.sv"
            marker = b"EXTERNAL_PREDICTOR" if platform == "oryukdo" else b"STRUCT_IST_BANKS"
            if top not in sources or marker not in sources[top]:
                raise RuntimeError(f"Selected revision does not contain the current {platform} Gen2 scheduler")
            versions[platform] = {"repository": URLS[platform], "commit": commit, "path": SOURCE_PATH,
                                 "sha256": {name: hashlib.sha256(data).hexdigest() for name, data in sources.items()}}
            target = GEN / f"platforms/{platform}/RTL"
            target.mkdir(parents=True, exist_ok=True)
            for old in target.glob("*.sv"):
                if old.name not in sources:
                    old.unlink()
            for name, data in sources.items():
                (target / name).write_bytes(data)
            print(f"{platform}: {commit} ({SOURCE_PATH}, {len(sources)} sources)")
    lines = ["// Generated by gen/scripts/sync_platforms.py. Do not edit by hand."]
    for platform, version in versions.items():
        for index, name in enumerate(version["sha256"]):
            data = (GEN / f"platforms/{platform}/RTL" / name).read_bytes()
            if hashlib.sha256(data).hexdigest() != version["sha256"][name]:
                raise RuntimeError(f"Pinned source mismatch: {platform}/{name}")
            lines.append(f"import {platform}_{index} from '../../../platforms/{platform}/RTL/{name}?raw';")
    lines.extend(["", "export const rtlSourceSets = {"])
    for platform, version in versions.items():
        lines.append(f"  {platform}: {{")
        for index, name in enumerate(version["sha256"]):
            lines.append(f"    {json.dumps(name)}: {platform}_{index},")
        lines.append("  },")
    lines.extend(["};", f"export const sourceVersions = {json.dumps(versions, indent=2)} as const;", ""])
    (GEN / "generator-app/src/utils/platformSources.ts").write_text("\n".join(lines), encoding="utf-8")
    lock.write_text(json.dumps(versions, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
